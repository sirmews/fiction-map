import { execFileSync } from "node:child_process"
import {
  cpSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs"
import { homedir, tmpdir } from "node:os"
import { join, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const crate = fileURLToPath(new URL("../../runtime-rs/", import.meta.url))
const generated = fileURLToPath(new URL("../src/wasm/generated/", import.meta.url))
const target = resolve(process.env.CARGO_TARGET_DIR ?? join(crate, "target"))
const cliRoot = join(target, "wasm-tools")
const cli = join(cliRoot, "bin", process.platform === "win32" ? "wasm-bindgen.exe" : "wasm-bindgen")
const version = (
  Bun.TOML.parse(readFileSync(join(crate, "Cargo.toml"), "utf8")) as {
    target: Record<string, { dependencies: Record<string, string> }>
  }
).target['cfg(target_arch = "wasm32")'].dependencies["wasm-bindgen"].replace(/^=/, "")
if (
  !existsSync(cli) ||
  execFileSync(cli, ["--version"], { encoding: "utf8" }).trim() !== `wasm-bindgen ${version}`
) {
  execFileSync(
    "cargo",
    ["install", "wasm-bindgen-cli", "--version", version, "--locked", "--root", cliRoot],
    { stdio: "inherit" },
  )
}

// Panic locations and inlined dependency source paths ship in the browser's
// Wasm. Give them stable names across developers, CI, and checkout locations.
const sysroot = execFileSync("rustc", ["--print", "sysroot"], { encoding: "utf8" }).trim()
const cargoHome = process.env.CARGO_HOME ?? join(homedir(), ".cargo")
const inheritedFlags =
  process.env.CARGO_ENCODED_RUSTFLAGS?.split("\x1f") ??
  process.env.RUSTFLAGS?.split(/\s+/).filter(Boolean) ??
  []
const flags = [
  ...inheritedFlags,
  `--remap-path-prefix=${sysroot}=/rust`,
  `--remap-path-prefix=${join(cargoHome, "registry", "src")}=/cargo/registry`,
  `--remap-path-prefix=${resolve(crate)}=/fiction-map/runtime`,
]

execFileSync(
  "cargo",
  [
    "build",
    "--locked",
    "--lib",
    "--target",
    "wasm32-unknown-unknown",
    "--release",
    "--target-dir",
    target,
  ],
  {
    cwd: crate,
    stdio: "inherit",
    env: { ...process.env, CARGO_ENCODED_RUSTFLAGS: flags.join("\x1f") },
  },
)
const staging = mkdtempSync(join(tmpdir(), "fiction-map-wasm-"))
try {
  execFileSync(
    cli,
    [
      join(target, "wasm32-unknown-unknown", "release", "fiction_map_runtime.wasm"),
      "--target",
      "web",
      "--omit-default-module-path",
      "--out-dir",
      staging,
      "--out-name",
      "runtime",
    ],
    { stdio: "inherit" },
  )
  const binary = readFileSync(join(staging, "runtime_bg.wasm"))
  const banner = "// GENERATED by build-wasm.ts. DO NOT EDIT.\n"
  writeFileSync(
    join(staging, "bytes.ts"),
    `${banner}export const bytes = "${binary.toString("base64")}"\n`,
  )
  // This package embeds the bytes so its public methods work on first import.
  rmSync(join(staging, "runtime_bg.wasm"))
  rmSync(join(staging, "runtime_bg.wasm.d.ts"), { force: true })
  for (const file of readdirSync(staging, { recursive: true, encoding: "utf8" })) {
    if (!file.endsWith(".js") && !file.endsWith(".d.ts")) continue
    const path = join(staging, file)
    writeFileSync(path, banner + readFileSync(path, "utf8"))
  }
  mkdirSync(generated, { recursive: true })
  rmSync(join(generated, "snippets"), { recursive: true, force: true })
  cpSync(staging, generated, { recursive: true })
} finally {
  rmSync(staging, { recursive: true, force: true })
}
